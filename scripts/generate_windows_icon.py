#!/usr/bin/env python3
"""Rebuild the pixel S SVG/ICO using only Python's standard library.

The six rows and gold colors match ui/about_skin.rs::about_wordmark. Each
resolution uses integer-sized cells; no antialiasing or runtime image codec.
Run with --check to verify that the checked-in assets are reproducible.
"""
import argparse
from pathlib import Path
import re
import struct
import zlib

ROOT = Path(__file__).resolve().parents[1]
SIZES = (16, 24, 32, 48, 64, 128, 256)
ROWS = (0b011110, 0b110000, 0b111100, 0b001111, 0b000011, 0b111110)


def rectangles(size):
    edge = max(1, size // 32)
    yield 0, 0, size, size, 0x353249
    for inset, light, dark in ((0, 0x88889F, 0x11111B), (edge, 0x5A5A70, 0x1B1B2A)):
        span = size - inset * 2
        yield inset, inset, span, edge, light
        yield inset, inset, edge, span, light
        yield inset, size - inset - edge, span, edge, dark
        yield size - inset - edge, inset, edge, span, dark
    cell = size // 8
    origin = size // 8
    shadow = max(1, size // 32)
    for y, row in enumerate(ROWS):
        for x in range(6):
            if row & (1 << (5 - x)):
                yield origin + x * cell + shadow, origin + y * cell + shadow, cell, cell, 0x786A38
                yield origin + x * cell, origin + y * cell, cell, cell, 0xD2BC6A


def rgba(size):
    pixels = bytearray(size * size * 4)
    for x, y, width, height, color in rectangles(size):
        pixel = bytes((color >> 16, (color >> 8) & 255, color & 255, 255))
        for yy in range(y, y + height):
            start = (yy * size + x) * 4
            pixels[start:start + width * 4] = pixel * width
    return bytes(pixels)


def png(size, pixels):
    def chunk(kind, data):
        return struct.pack('>I', len(data)) + kind + data + struct.pack('>I', zlib.crc32(kind + data))
    rows = b''.join(b'\0' + pixels[y * size * 4:(y + 1) * size * 4] for y in range(size))
    return (b'\x89PNG\r\n\x1a\n'
            + chunk(b'IHDR', struct.pack('>IIBBBBB', size, size, 8, 6, 0, 0, 0))
            + chunk(b'IDAT', zlib.compress(rows, 9)) + chunk(b'IEND', b''))


def dib(size, pixels):
    # ICO bitmap rows are bottom-up BGRA, followed by the 1-bit AND mask.
    bitmap = bytearray()
    for y in range(size - 1, -1, -1):
        for x in range(size):
            r, g, b, a = pixels[(y * size + x) * 4:(y * size + x + 1) * 4]
            bitmap.extend((b, g, r, a))
    mask = bytes(((size + 31) // 32) * 4 * size)
    return struct.pack('<IiiHHIIiiII', 40, size, size * 2, 1, 32, 0, len(bitmap), 0, 0, 0, 0) + bitmap + mask


def assets():
    source = (ROOT / 'src/ui/about_skin.rs').read_text(encoding='utf-8')
    wordmark = source[source.index('fn about_wordmark'):]
    rows = tuple(int(row, 2) for row in re.search(r'let rows = \[(.*?)\]', wordmark).group(1).replace('0b', '').split(', '))
    if rows != ROWS or '0xd2bc6a' not in wordmark or '0x786a38' not in wordmark:
        raise ValueError('The About monogram changed; synchronize the icon generator deliberately')
    svg = ('<svg xmlns="http://www.w3.org/2000/svg" width="256" height="256" viewBox="0 0 32 32" shape-rendering="crispEdges">\n'
           '  <!-- Angular gold S from src/ui/about_skin.rs; generated by scripts/generate_windows_icon.py. -->\n')
    for x, y, width, height, color in rectangles(32):
        svg += f'  <rect x="{x}" y="{y}" width="{width}" height="{height}" fill="#{color:06x}"/>\n'
    svg += '</svg>\n'
    frames = [png(size, rgba(size)) if size == 256 else dib(size, rgba(size)) for size in SIZES]
    offset = 6 + len(SIZES) * 16
    directory = bytearray(struct.pack('<HHH', 0, 1, len(SIZES)))
    for size, frame in zip(SIZES, frames):
        directory.extend(struct.pack('<BBBBHHII', size % 256, size % 256, 0, 0, 1, 32, len(frame), offset))
        offset += len(frame)
    return {'spotiamp.svg': svg.encode(), 'spotiamp.ico': bytes(directory) + b''.join(frames)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, content in assets().items():
        path = ROOT / 'assets/windows' / name
        if args.check:
            # Windows Git checkouts may use CRLF for the text SVG. ICO bytes
            # remain exact; universal-newline reading only normalizes the SVG.
            current = path.read_text(encoding='utf-8').encode() if path.suffix == '.svg' else path.read_bytes()
            if current != content:
                raise SystemExit(f'{path.relative_to(ROOT)} is stale; run {Path(__file__).name}')
        else:
            path.write_bytes(content)
        print(f'{path.relative_to(ROOT)}: {len(content)} bytes')


if __name__ == '__main__':
    main()
